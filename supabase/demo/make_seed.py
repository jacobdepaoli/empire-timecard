# ── T&M tickets ($120/hr, 30% materials markup, 8.265% tax on the subtotal) ──
def tm(n, num, job, who, day, cust, phone, addr, complaint, performed, resolution, labor, mats, pics, signer):
    lt = sum(r * h for _, r, h in labor)
    ms = sum(qn * c for qn, _, c in mats)
    mk = round(ms * 0.30, 2)
    sub = lt + ms + ms * 0.30
    tax = sub * 8.265 / 100
    grand = round(sub + tax, 2)
    lab = [{"name": FULL[x], "rate": r, "hours": h} for x, r, h in labor]
    mat = [{"qty": qn, "desc": ds, "cost": c, "photo": ""} for qn, ds, c in mats]
    ph = [{"src": pic(p), "caption": cap} for p, cap in pics]
    jid, jname = JOBS[job][0], (cust if job == "svc" else JOBS[job][1])
    out.append(
        "insert into public.tm_sheets (id, tm_number, job_id, job_name, employee_id, employee_name, work_date, customer_name, customer_phone, site_address, "
        "complaint, work_performed, resolution, labor, materials, photos, markup_rate, tax_rate, labor_total, materials_total, materials_markup, tax_amount, grand_total, "
        f"customer_sign_name, sign_date, status, created_at) values ({q(d(n))}, {q(num)}, {q(jid)}, {q(jname)}, {q(E[who])}, {q(NAME[who])}, {q(day)}, {q(cust)}, {q(phone)}, {q(addr)}, "
        f"{q(complaint)}, {q(performed)}, {q(resolution)}, {q(json.dumps(lab))}::jsonb, {q(json.dumps(mat))}::jsonb, {q(json.dumps(ph))}::jsonb, 30, 8.265, "
        f"{round(lt,2)}, {round(ms,2)}, {mk}, {round(tax,2)}, {grand}, {q(signer)}, {q(day)}, 'Complete', {ts(day, '15:45')});")
    return grand

